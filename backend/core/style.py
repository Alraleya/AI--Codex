def expand_style(style: str, extra_constraints: str = "") -> str:
    if not isinstance(style, str) or not style.strip():
        raise ValueError("style is required")
    style = style.strip()
    try:
        base = STYLE_REGISTRY[style]
    except KeyError:
        # A provided script may carry a project-specific visual direction that
        # is not one of the preset labels. Preserve that direction verbatim;
        # never replace it with an unrelated preset.
        base = style
    extra = extra_constraints.strip()
    return base if not extra else "%s；补充约束：%s" % (base, extra)
